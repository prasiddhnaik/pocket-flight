"""Tessellate the CAD master, retaining labels and assembly paths for the game."""
import json
from pathlib import Path
from stormbird import stormbird, HINGES
from mechanisms import MECHANISMS

root = Path(__file__).resolve().parents[1]
parts = []


def visit(shape, parents):
    if shape.children:
        for child in shape.children:
            visit(child, parents + [shape.label])
        return
    try:
        from OCP.BRepMesh import BRepMesh_IncrementalMesh
        from OCP.BRepTools import BRepTools
        # Use an absolute chord tolerance in CAD millimetres. build123d's default
        # relative meshing can discard faces on thin, long door panels.
        BRepTools.Clean_s(shape.wrapped)
        BRepMesh_IncrementalMesh(shape.wrapped, .5, False, .20, True)
        vertices, faces = shape.tessellate(2.0, .20)
    except Exception as error:
        raise RuntimeError('Cannot mesh '+ '/'.join([*parents, shape.label])) from error
    parts.append({
        'name': shape.label,
        'parents': parents,
        'color': list(shape.color) if shape.color else None,
        'vertices': [[v.X / 1000, v.Z / 1000, -v.Y / 1000] for v in vertices],
        'faces': [list(f) for f in faces],
    })


visit(stormbird(), [])
target = root / 'GLB/cad-transfer.json'
hinges = {name: {'point': [d['point'][0], d['point'][2], -d['point'][1]],
                 'axis': [d['axis'][0], d['axis'][2], -d['axis'][1]]}
          for name, d in HINGES.items()}
def convert(point): return [point[0], point[2], -point[1]]
mechanisms = {
    'canopy': {**MECHANISMS['canopy'], 'point': convert(MECHANISMS['canopy']['point']), 'axis': convert(MECHANISMS['canopy']['axis'])},
    'legs': [{**d, 'point': convert(d['point']), 'axis': convert(d['axis']),
              **({'swivel':{**d['swivel'],'point':convert(d['swivel']['point']),'axis':convert(d['swivel']['axis'])}} if 'swivel' in d else {}),
              'torque': {**d['torque'], **{key:convert(d['torque'][key]) for key in ['a','elbow','b']}}} for d in MECHANISMS['legs']],
    'doors': [{**d, 'point': convert(d['point']), 'axis': convert(d['axis'])} for d in MECHANISMS['doors']],
    'segments': {n: [convert(a), convert(c)] for n,(a,c) in MECHANISMS['segments'].items()},
}
for leg in MECHANISMS['legs']:
    hinges[leg['torque']['pin']]={'point':convert(leg['torque']['elbow']), 'axis':[1,0,0]}
target.write_text(json.dumps({'units': 'metres', 'up': 'Y', 'forward': '-Z',
                             'hinges': hinges, 'mechanisms': mechanisms, 'parts': parts}, separators=(',', ':')))
print(json.dumps({'parts': len(parts), 'triangles': sum(len(p['faces']) for p in parts), 'transfer': str(target)}))

# Render-module handles target exact occurrence paths, including repeated wheel labels.
refs = {}
def occurrences(shape, ref='o1'):
    animated=[MECHANISMS['canopy'], *MECHANISMS['legs'], *MECHANISMS['doors'],
              *[d['swivel'] for d in MECHANISMS['legs'] if 'swivel' in d]]
    if shape.label in MECHANISMS['segments'] or shape.label in {d['name'] for d in animated}:
        refs[shape.label] = '#'+ref
    for index, child in enumerate(shape.children, 1):
        occurrences(child, ref+'.'+str(index))
occurrences(stormbird())
template=Path(__file__).with_name('animation-template.js').read_text()
module=template.replace('__MECHANISMS__',json.dumps(MECHANISMS)).replace('__REFS__',json.dumps(refs))
(root/'src/animation_data.py').write_text('# Generated source declaration; regenerated by export_transfer.py.\nANIMATION = '+repr(module)+'\n')
print(json.dumps({'animation_declaration': str(root/'src/animation_data.py'), 'handles':len(refs)}))
